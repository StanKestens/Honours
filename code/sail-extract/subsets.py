"""Cut small, self-contained subsets out of out/encdec_clauses.json.

    python3 subsets.py            # writes out/subsets/*.txt and ../decision-tree/Subsets.v

Levels (each adds one new difficulty):

  rv32i_core  base_insts.sail clauses WITHOUT any guard. No guards at all; the only
              overlap is FENCE_TSO (a special case of FENCE), so first-match order matters once.
  rv32i       all of base_insts.sail under the fixed configuration RV32 (xlen = 32, Sv32 present).
              Guards are folded into bits: rows with `xlen == 64` disappear, the other guards
              become extra fixed bits / or-patterns (see FOLD below).

Rows keep Sail's first-match order. Field extraction and guards that are not folded are out of scope.
"""
import json, os, itertools

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'out', 'encdec_clauses.json')
OUT_TXT = os.path.join(HERE, 'out', 'subsets')
OUT_V = os.path.join(HERE, '..', 'decision-tree', 'Subsets.v')

def bits(msb, lsb, allowed):
    """Or-pattern on field [msb:lsb] with the given allowed values (as ints)."""
    m = ((1 << (msb - lsb + 1)) - 1) << lsb
    return [(m, a << lsb) for a in allowed]

# RV32 (xlen_bytes = 4). word_width encoding in bits [13:12]: 00=byte 01=half 10=word 11=double.
FOLD = {
    # xlen == 64 | shamt[5] == 0b0   ->  bit 25 = 0
    'xlen == 64 | shamt[5] == 0b0': [(1 << 25, 0)],
    # valid_load_encdec(width, is_unsigned) = width < xlen_bytes | (not(is_unsigned) & width <= xlen_bytes)
    # bits [14:12] = is_unsigned @ width  ->  000 001 010 100 101   (base_insts.sail:274)
    'valid_load_encdec(width, is_unsigned)': bits(14, 12, [0b000, 0b001, 0b010, 0b100, 0b101]),
    # width <= xlen_bytes  ->  width in {00, 01, 10}
    'width <= xlen_bytes': bits(13, 12, [0b00, 0b01, 0b10]),
    # virtual_memory_supported() | ...  ->  true under the chosen configuration (Sv32 present)
    'virtual_memory_supported() | not(config extensions.Svbare.sfence_vma_illegal_if_svbare_only : bool)': [(0, 0)],
}
DROP = {'xlen == 64'}

def guard(c):
    return ' & '.join(c['guard_config'] + c['guard_mixed'] + c['guard_field'])

def rows_of(c, extra):
    """All (mask, value) alternatives of clause c, intersected with the or-pattern `extra`."""
    out = []
    for (m, v), (em, ev) in itertools.product(c['alternatives'], extra):
        m, v = int(m, 16), int(v, 16)
        if (v & em) != (ev & m):      # conflicting fixed bits: empty
            continue
        out.append((m | em, v | ev))
    return out

def level_rv32i_core(C):
    return [(c, rows_of(c, [(0, 0)])) for c in C if 'base_insts' in c['file'] and not guard(c)]

def level_rv32i(C):
    res = []
    for c in C:
        if 'base_insts' not in c['file']: continue
        g = guard(c)
        if g in DROP: continue
        if g and g not in FOLD:
            raise SystemExit('unfolded guard in rv32i: %r (%s)' % (g, c['constructor']))
        res.append((c, rows_of(c, FOLD[g] if g else [(0, 0)])))
    return res

LEVELS = [('rv32i_core', level_rv32i_core), ('rv32i', level_rv32i)]

def pattern(m, v, w=32):
    return ''.join(('1' if v >> i & 1 else '0') if m >> i & 1 else '-' for i in reversed(range(w)))

def overlaps(rows):
    """Pairs (earlier, later) of rows that some word matches both."""
    res = []
    for i, (na, ma, va) in enumerate(rows):
        for nb, mb, vb in rows[:i]:
            cm = ma & mb
            if (va & cm) == (vb & cm): res.append((nb, na))
    return res

def main():
    C = [c for c in json.load(open(SRC))['clauses'] if c['mapping'] == 'encdec']
    os.makedirs(OUT_TXT, exist_ok=True)
    v = ['(** Generated by code/sail-extract/subsets.py. Do not edit.',
         '    Small subsets of [encdec_rows], in Sail\'s first-match order. See subsets.py for what',
         '    each level contains and how guards were folded into bits. *)', '',
         'From Stdlib Require Import NArith String List.', 'From DTree Require Import EncdecRows.',
         'Import ListNotations.', 'Local Open Scope string_scope.', 'Local Open Scope N_scope.']
    for name, f in LEVELS:
        lvl = f(C)
        flat = []
        for c, rs in lvl:
            for i, (m, val) in enumerate(rs):
                nm = '%s@%d' % (c['constructor'], c['line']) + ('#%d' % i if len(rs) > 1 else '')
                flat.append((nm, m, val, c))
        ov = overlaps([(n, m, val) for n, m, val, _ in flat])
        with open(os.path.join(OUT_TXT, name + '.txt'), 'w') as fh:
            fh.write('# %s: %d clauses, %d rows, %d overlapping pairs\n' % (name, len(lvl), len(flat), len(ov)))
            for n, m, val, c in flat:
                fh.write('%s  %-18s %s\n' % (pattern(m, val), n, ('  (was: when %s)' % guard(c)) if guard(c) else ''))
            for a, b in ov:
                fh.write('# overlap: %s is shadowed on some words by earlier %s\n' % (b, a))
        v.append('\n(** %s: %d clauses, %d rows, %d overlapping pair(s)%s. *)' % (
            name, len(lvl), len(flat), len(ov), (': ' + ', '.join('%s before %s' % p for p in ov)) if ov else ''))
        v.append('Definition %s_rows : list raw_row := [' % name)
        v.append(';\n'.join('  mk_raw "%s" "%s" %d %d %d' % (n, c['file'].replace('model/', ''), c['order'], m, val)
                            for n, m, val, c in flat))
        v.append('].')
        print('%-11s %3d clauses %3d rows  overlaps: %s' % (name, len(lvl), len(flat), ov or 'none'))
    open(OUT_V, 'w').write('\n'.join(v) + '\n')

if __name__ == '__main__':
    main()
